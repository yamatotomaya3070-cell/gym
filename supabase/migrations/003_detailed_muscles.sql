-- ============================================================
-- GymNote – Migration 003: 詳細筋肉フィルター対応
-- category → 6大分類（chest/back/shoulder/arm/leg/core）
-- primary_muscles → 詳細筋肉名配列（複数可）
-- ============================================================

-- Step 1: 002の CHECK 制約を削除
ALTER TABLE exercises DROP CONSTRAINT IF EXISTS exercises_category_check;

-- Step 2: カスタム種目の旧カテゴリを6大分類にマッピング
UPDATE exercises SET category = 'chest'    WHERE is_custom = true AND category IN ('chest_upper','chest_mid','chest_lower');
UPDATE exercises SET category = 'back'     WHERE is_custom = true AND category IN ('back_lat','back_trap');
UPDATE exercises SET category = 'shoulder' WHERE is_custom = true AND category IN ('shoulder_front','shoulder_mid','shoulder_rear');
UPDATE exercises SET category = 'arm'      WHERE is_custom = true AND category IN ('biceps','triceps','forearm');
UPDATE exercises SET category = 'leg'      WHERE is_custom = true AND category IN ('quad','hamstring','glute','calf');
-- core → core（変更なし）

-- Step 3: プリセット種目を全削除（新データで再投入）
DELETE FROM exercises WHERE is_custom = false;

-- Step 4: 新 CHECK 制約（6大分類）
ALTER TABLE exercises ADD CONSTRAINT exercises_category_check
  CHECK (category IN ('chest','back','shoulder','arm','leg','core'));

